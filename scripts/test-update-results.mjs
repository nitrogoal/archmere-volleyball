import fs from 'node:fs';
import assert from 'node:assert/strict';
import {merge,validate,total} from './update-results.mjs';
const d=JSON.parse(fs.readFileSync(new URL('../dist/data.json',import.meta.url)));
validate(d);
const original=structuredClone(d);
const game=structuredClone(d.games.find(g=>g.id==='404441'));
const rows=d.stats.filter(s=>s.id===game.id).map(s=>({name:s.name,values:s.values}));
assert.equal(merge(d,{games:[{game,stats:rows,complete:true}]}).changed,false,'Existing result must be a no-op');
const batch={games:[{game:{...game,id:'999999999',url:'https://www.aukssports.com/game999999999',date:'10/16/26'},stats:rows,complete:true}]};
const one=merge(d,batch);assert(one.changed);const two=merge(one.data,batch);assert.equal(two.changed,false,'Repeated import must be a no-op');
assert.equal(one.data.stats.length,d.stats.length+rows.length);
assert.deepEqual(total(one.data.stats).map((v,i)=>v-total(d.stats)[i]),total(rows).map(v=>v??0));
assert.throws(()=>merge(d,{games:[batch.games[0],batch.games[0]]}),/Duplicate incoming game/);
assert.throws(()=>merge(d,{games:[{...batch.games[0],stats:[rows[0],rows[0]]}]}),/Duplicate incoming player/);
assert.throws(()=>merge(d,{games:[{...batch.games[0],complete:false}]}),/Incomplete/);
assert.throws(()=>merge(d,{games:[{...batch.games[0],stats:[{name:'Unverified Player',values:[1,0,0,0,0]}]}]}),/Unknown player/);
const lost=structuredClone(rows);const r=lost.find(r=>r.values.some(v=>v!==null));r.values[r.values.findIndex(v=>v!==null)]=null;
assert.throws(()=>merge(d,{games:[{game,stats:lost,complete:true}]}),/lost a known statistic/);
const protectedData=structuredClone(d);protectedData.resolvedIssues.push({id:game.id,name:rows[0].name,rows:[rows[0]]});
const altered=structuredClone(rows);altered[0].values[0]=(altered[0].values[0]??0)+1;
assert.throws(()=>merge(protectedData,{games:[{game,stats:altered,complete:true}]}),/reviewed correction/);
assert.deepEqual(d,original,'Tests must not mutate production data');
console.log('PASS: no-op, new result, repeated import, totals delta, duplicate game/player rejection, incomplete capture, unknown name, missing value and correction protection.');
